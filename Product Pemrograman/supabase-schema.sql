-- LOKA starter schema for Supabase (PostgreSQL)
-- Jalankan melalui Supabase SQL Editor setelah meninjau kebutuhan autentikasi/RLS.
-- Schema ini adalah fondasi; aplikasi frontend belum terhubung ke Supabase.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  sku text unique,
  category text,
  price numeric(14,2) not null default 0 check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  emoji text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id text primary key,
  customer text not null,
  phone text,
  product text not null,
  qty integer not null default 1 check (qty > 0),
  channel text not null check (channel in ('WhatsApp','Instagram','Shopee','TikTok Shop','Offline')),
  status text not null default 'Menunggu'
    check (status in ('Menunggu','Diproses','Siap Dikirim','Selesai','Dibatalkan')),
  total numeric(14,2) not null default 0 check (total >= 0),
  order_date date not null default current_date,
  address text,
  created_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  title text not null,
  message text not null,
  icon text default '🔔',
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

